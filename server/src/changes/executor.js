import { query } from "../db.js";

export async function executeChangeJob(job, github, ai) {
  const token = await step(job.id, "obtaining_installation_token", () => github.createInstallationToken(job.installation_id));
  const branch = `execution-ai/change-${job.sequence}`;
  const results = [];
  for (const type of job.repositories) {
    const key = type.toLowerCase();
    const repository = job.generated_repositories.find((item) => item.type === type);
    if (!repository) throw Object.assign(new Error(`${type} repository is missing from the generated baseline`), { retryable: false });
    const files = await step(job.id, `reading_${key}_repository`, () => github.readTextFiles({ token, owner: job.external_owner, repository: repository.name, branch: job.base_branch }));
    const patch = await step(job.id, `planning_${key}_changes`, () => ai.generatePatch({ project: job.project_data, changeRequest: job, repository, files }));
    const commit = await step(job.id, `committing_${key}_changes`, () => github.commitFiles({ token, owner: job.external_owner, repository: repository.name, branch, baseBranch: job.base_branch, files: Object.fromEntries(patch.files.map((file) => [file.path, file.content])), message: `feat: change ${job.sequence} - ${job.title}` }));
    let pullRequest = null;
    try {
      pullRequest = await step(job.id, `opening_${key}_pull_request`, () => github.ensurePullRequest({ token, owner: job.external_owner, repository: repository.name, branch, baseBranch: job.base_branch, title: `Change ${job.sequence}: ${job.title}`, body: `${job.discussion}\n\n## Acceptance criteria\n${job.acceptance_criteria.map((item) => `- ${item}`).join("\n")}\n\nGenerated by Execution AI.` }));
    } catch (error) {
      if (error.status !== 403) throw error;
    }
    const result = { type, name: repository.name, summary: patch.summary, changedFiles: patch.files.map((file) => file.path), ...commit, pullRequestUrl: pullRequest?.html_url || null };
    results.push(result);
    await query("update change_jobs set result = $1, updated_at = now() where id = $2", [{ branch, repositories: results }, job.id]);
  }
  const result = { branch, repositories: results, completedAt: new Date().toISOString() };
  await query("update change_jobs set status = 'ready', current_step = 'complete', result = $1, error = null, locked_at = null, locked_by = null, updated_at = now() where id = $2", [result, job.id]);
  await query("update change_requests set status = 'implemented', updated_at = now() where id = $1", [job.change_request_id]);
  return result;
}

async function step(jobId, name, action) {
  await query("update change_jobs set status = 'running', current_step = $1, updated_at = now() where id = $2", [name, jobId]);
  return action();
}
