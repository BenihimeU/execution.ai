import jwt from "jsonwebtoken";
import { config } from "../config.js";
import { templateFiles } from "./templates.js";

export class GitHubProvider {
  constructor({ appId = config.githubAppId, privateKey = config.githubPrivateKey, apiUrl = config.githubApiUrl } = {}) {
    this.appId = appId; this.privateKey = privateKey; this.apiUrl = apiUrl;
  }

  assertConfigured() {
    if (!this.appId || !this.privateKey) {
      const error = new Error("GitHub App credentials are not configured"); error.code = "GITHUB_APP_NOT_CONFIGURED"; error.retryable = false; throw error;
    }
  }

  createAppJwt() {
    this.assertConfigured();
    const now = Math.floor(Date.now() / 1000);
    return jwt.sign({ iat: now - 60, exp: now + 540, iss: this.appId }, this.privateKey, { algorithm: "RS256" });
  }

  async getInstallation(installationId) {
    return this.request(`/app/installations/${installationId}`, { token: this.createAppJwt() });
  }

  async createInstallationToken(installationId) {
    this.assertConfigured();
    const appJwt = this.createAppJwt();
    const response = await this.request(`/app/installations/${installationId}/access_tokens`, { method: "POST", token: appJwt });
    return response.token;
  }

  async ensureRepository({ token, owner, accountType, specification }) {
    const existing = await this.request(`/repos/${owner}/${specification.name}`, { token, allow404: true });
    if (existing) return { ...existing, type: specification.type };
    const createPath = accountType === "User" ? "/user/repos" : `/orgs/${owner}/repos`;
    const created = await this.request(createPath, { method: "POST", token, body: { name: specification.name, description: `${specification.type} application generated by Execution AI`, private: specification.visibility !== "public", auto_init: true, has_issues: true } });
    return { ...created, type: specification.type };
  }

  async ensureTemplateFiles({ token, owner, repository, projectName }) {
    const files = templateFiles(repository.type, projectName);
    for (const [path, content] of Object.entries(files)) {
      const current = await this.request(`/repos/${owner}/${repository.name}/contents/${encodePath(path)}`, { token, allow404: true });
      const encoded = Buffer.from(content).toString("base64");
      if (current?.content && Buffer.from(current.content.replace(/\n/g, ""), "base64").toString() === content) continue;
      await this.request(`/repos/${owner}/${repository.name}/contents/${encodePath(path)}`, { method: "PUT", token, body: { message: current ? `Update ${path}` : `Add ${path}`, content: encoded, ...(current?.sha ? { sha: current.sha } : {}) } });
    }
  }

  async ensureEnvironment({ token, owner, repository, environment }) {
    const body = environment.protection === "automatic"
      ? { deployment_branch_policy: null }
      : { deployment_branch_policy: { protected_branches: true, custom_branch_policies: false } };
    await this.request(`/repos/${owner}/${repository.name}/environments/${encodeURIComponent(environment.name)}`, { method: "PUT", token, body });
  }

  async request(path, { method = "GET", token, body, allow404 = false } = {}) {
    const response = await fetch(`${this.apiUrl}${path}`, { method, headers: { Accept: "application/vnd.github+json", Authorization: `Bearer ${token}`, "User-Agent": "Execution-AI-Provisioner", "X-GitHub-Api-Version": "2022-11-28", ...(body ? { "Content-Type": "application/json" } : {}) }, body: body ? JSON.stringify(body) : undefined });
    if (allow404 && response.status === 404) return null;
    if (!response.ok) {
      const payload = await response.json().catch(() => ({}));
      const message = payload.message || `GitHub request failed (${response.status})`;
      const error = new Error(message); error.status = response.status; error.documentationUrl = payload.documentation_url || null; error.retryAfter = Number(response.headers.get("retry-after") || 0); error.rateLimitRemaining = response.headers.get("x-ratelimit-remaining"); error.rateLimitReset = response.headers.get("x-ratelimit-reset"); error.retryable = response.status === 429 || response.status >= 500 || (response.status === 403 && /rate limit|abuse|temporarily blocked/i.test(message)); throw error;
    }
    if (response.status === 204) return null;
    return response.json();
  }
}

function encodePath(path) { return path.split("/").map(encodeURIComponent).join("/"); }
