import jwt from "jsonwebtoken";
import { config } from "../config.js";
import { templateFiles } from "./templates.js";

export class GitHubProvider {
  constructor({ appId = config.githubAppId, privateKey = config.githubPrivateKey, apiUrl = config.githubApiUrl } = {}) {
    this.appId = appId; this.privateKey = privateKey; this.apiUrl = apiUrl;
  }

  assertConfigured() {
    if (!this.appId || !this.privateKey) {
      const error = new Error("GitHub App credentials are not configured"); error.code = "GITHUB_APP_NOT_CONFIGURED"; error.retryable = false; throw error;
    }
  }

  createAppJwt() {
    this.assertConfigured();
    const now = Math.floor(Date.now() / 1000);
    return jwt.sign({ iat: now - 60, exp: now + 540, iss: this.appId }, this.privateKey, { algorithm: "RS256" });
  }

  async getInstallation(installationId) {
    return this.request(`/app/installations/${installationId}`, { token: this.createAppJwt() });
  }

  async createInstallationToken(installationId) {
    this.assertConfigured();
    const appJwt = this.createAppJwt();
    const response = await this.request(`/app/installations/${installationId}/access_tokens`, { method: "POST", token: appJwt });
    return response.token;
  }

  async ensureRepository({ token, owner, accountType, specification }) {
    const existing = await this.request(`/repos/${owner}/${specification.name}`, { token, allow404: true });
    if (existing) return { ...existing, type: specification.type };
    const createPath = accountType === "User" ? "/user/repos" : `/orgs/${owner}/repos`;
    const created = await this.request(createPath, { method: "POST", token, body: { name: specification.name, description: `${specification.type} application generated by Execution AI`, private: specification.visibility !== "public", auto_init: true, has_issues: true } });
    return { ...created, type: specification.type };
  }

  async getRepository({ token, owner, repository }) {
    return this.request(`/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}`, { token });
  }

  async setDefaultBranch({ token, owner, repository, branch }) {
    return this.request(`/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}`, { method: "PATCH", token, body: { default_branch: branch } });
  }

  async ensureTemplateFiles({ token, owner, repository, projectName }) {
    const files = templateFiles(repository.type, projectName);
    return this.ensureFiles({ token, owner, repository: repository.name, files });
  }

  async ensureFiles({ token, owner, repository, files, branch }) {
    for (const [path, content] of Object.entries(files)) {
      const suffix = branch ? `?ref=${encodeURIComponent(branch)}` : "";
      const current = await this.request(`/repos/${owner}/${repository}/contents/${encodePath(path)}${suffix}`, { token, allow404: true });
      const encoded = Buffer.from(content).toString("base64");
      if (current?.content && Buffer.from(current.content.replace(/\n/g, ""), "base64").toString() === content) continue;
      await this.request(`/repos/${owner}/${repository}/contents/${encodePath(path)}`, { method: "PUT", token, body: { message: current ? `chore: update ${path}` : `chore: add ${path}`, content: encoded, ...(current?.sha ? { sha: current.sha } : {}), ...(branch ? { branch } : {}) } });
    }
  }

  async ensureEnvironment({ token, owner, repository, environment }) {
    const body = environment.protection === "automatic"
      ? { deployment_branch_policy: null }
      : environment.protection === "custom"
        ? { deployment_branch_policy: { protected_branches: false, custom_branch_policies: true } }
        : { deployment_branch_policy: { protected_branches: true, custom_branch_policies: false } };
    await this.request(`/repos/${owner}/${repository.name}/environments/${encodeURIComponent(environment.name)}`, { method: "PUT", token, body });
  }

  async ensureEnvironmentBranchPolicy({ token, owner, repository, environment, branch }) {
    const path = `/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}/environments/${encodeURIComponent(environment)}/deployment-branch-policies`;
    const policies = await this.request(`${path}?per_page=100`, { token });
    if (policies.branch_policies?.some((policy) => policy.name === branch && policy.type === "branch")) return;
    await this.request(path, { method: "POST", token, body: { name: branch, type: "branch" } });
  }

  async commitFiles({ token, owner, repository, branch, baseBranch = "main", files, message }) {
    const repositoryPath = `/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}`;
    const referenceName = `heads/${encodePath(branch)}`;
    const readReferencePath = `${repositoryPath}/git/ref/${referenceName}`;
    const updateReferencePath = `${repositoryPath}/git/refs/${referenceName}`;
    let reference = await this.request(readReferencePath, { token, allow404: true });
    if (!reference) {
      const base = await this.request(`${repositoryPath}/git/ref/heads/${encodePath(baseBranch)}`, { token });
      reference = await this.request(`${repositoryPath}/git/refs`, { method: "POST", token, body: { ref: `refs/heads/${branch}`, sha: base.object.sha } });
    }
    const parent = reference.object.sha;
    const commit = await this.request(`/repos/${owner}/${repository}/git/commits/${parent}`, { token });
    const tree = [];
    for (const [path, content] of Object.entries(files)) {
      const blob = await this.request(`/repos/${owner}/${repository}/git/blobs`, { method: "POST", token, body: { content, encoding: "utf-8" } });
      tree.push({ path, mode: "100644", type: "blob", sha: blob.sha });
    }
    const nextTree = await this.request(`/repos/${owner}/${repository}/git/trees`, { method: "POST", token, body: { base_tree: commit.tree.sha, tree } });
    const nextCommit = await this.request(`/repos/${owner}/${repository}/git/commits`, { method: "POST", token, body: { message, tree: nextTree.sha, parents: [parent] } });
    await this.request(updateReferencePath, { method: "PATCH", token, body: { sha: nextCommit.sha, force: false } });
    return { branch, commitSha: nextCommit.sha, url: `https://github.com/${owner}/${repository}/tree/${branch}` };
  }

  async readTextFiles({ token, owner, repository, branch, maxBytes = 300_000 }) {
    const repositoryPath = `/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}`;
    const reference = await this.request(`${repositoryPath}/git/ref/heads/${encodePath(branch)}`, { token });
    const commit = await this.request(`${repositoryPath}/git/commits/${reference.object.sha}`, { token });
    const tree = await this.request(`${repositoryPath}/git/trees/${commit.tree.sha}?recursive=1`, { token });
    const allowed = /\.(js|jsx|ts|tsx|json|css|scss|html|md|ya?ml|sql)$/i;
    const candidates = (tree.tree || []).filter((item) => item.type === "blob" && allowed.test(item.path) && !/(^|\/)(node_modules|dist|\.env|package-lock\.json)(\/|$)/.test(item.path));
    const files = {};
    let total = 0;
    for (const item of candidates) {
      if (total + Number(item.size || 0) > maxBytes) continue;
      const blob = await this.request(`${repositoryPath}/git/blobs/${item.sha}`, { token });
      const content = Buffer.from((blob.content || "").replace(/\n/g, ""), "base64").toString("utf8");
      total += Buffer.byteLength(content); files[item.path] = content;
    }
    return files;
  }

  async ensurePullRequest({ token, owner, repository, branch, baseBranch, title, body }) {
    const repositoryPath = `/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}`;
    const existing = await this.request(`${repositoryPath}/pulls?state=open&head=${encodeURIComponent(`${owner}:${branch}`)}&base=${encodeURIComponent(baseBranch)}`, { token });
    if (existing[0]) return existing[0];
    return this.request(`${repositoryPath}/pulls`, { method: "POST", token, body: { title, body, head: branch, base: baseBranch } });
  }

  async dispatchWorkflow({ token, owner, repository, workflow = "deploy.yml", ref, inputs }) {
    return this.request(`/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}/actions/workflows/${encodeURIComponent(workflow)}/dispatches`, { method: "POST", token, body: { ref, inputs } });
  }

  async ensurePagesSite({ token, owner, repository }) {
    const path = `/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}/pages`;
    try {
      const existing = await this.request(path, { token, allow404: true });
      if (existing) return existing;
      return await this.request(path, { method: "POST", token, body: { build_type: "workflow" } });
    }
    catch (error) {
      if (error.status === 403) {
        error.message = "GitHub Pages could not be enabled. Give the Execution AI GitHub App Pages: read/write and Administration: read/write permissions, approve the updated organization installation, then retry.";
      }
      throw error;
    }
  }

  async mergePullRequest({ token, owner, repository, pullNumber }) {
    return this.request(`/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}/pulls/${pullNumber}/merge`, { method: "PUT", token, body: { merge_method: "squash" } });
  }

  async getWorkflowRuns({ token, owner, repository, workflow = "deploy.yml", branch, event = "workflow_dispatch" }) {
    const query = new URLSearchParams({ branch, per_page: "20" });
    if (event) query.set("event", event);
    const result = await this.request(`/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}/actions/workflows/${encodeURIComponent(workflow)}/runs?${query}`, { token });
    return result.workflow_runs || [];
  }

  async getWorkflowRun({ token, owner, repository, runId }) {
    return this.request(`/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}/actions/runs/${runId}`, { token });
  }

  async request(path, { method = "GET", token, body, allow404 = false } = {}) {
    const response = await fetch(`${this.apiUrl}${path}`, { method, headers: { Accept: "application/vnd.github+json", Authorization: `Bearer ${token}`, "User-Agent": "Execution-AI-Provisioner", "X-GitHub-Api-Version": "2022-11-28", ...(body ? { "Content-Type": "application/json" } : {}) }, body: body ? JSON.stringify(body) : undefined });
    if (allow404 && response.status === 404) return null;
    if (!response.ok) {
      const payload = await response.json().catch(() => ({}));
      const message = payload.message || `GitHub request failed (${response.status})`;
      const error = new Error(message); error.status = response.status; error.documentationUrl = payload.documentation_url || null; error.retryAfter = Number(response.headers.get("retry-after") || 0); error.rateLimitRemaining = response.headers.get("x-ratelimit-remaining"); error.rateLimitReset = response.headers.get("x-ratelimit-reset"); error.retryable = response.status === 429 || response.status >= 500 || (response.status === 403 && /rate limit|abuse|temporarily blocked/i.test(message)); throw error;
    }
    if (response.status === 204) return null;
    return response.json();
  }
}

function encodePath(path) { return path.split("/").map(encodeURIComponent).join("/"); }
